const { test } = require('node:test');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const { fixture } = require('./helpers');
const { hashPassword } = require('../api/src/auth/credentials');
const { totp } = require('../api/src/auth/mfa-crypto');

test('SPA MFA works end-to-end with real API and isolated database at mobile width', async t => {
  const app = await fixture({ auth: {} });
  t.after(() => app.close());
  const email = 'mfa-browser@example.com', password = 'browser-mfa-password';
  await app.prisma.user.create({ data: { email, passwordHash: await hashPassword(password), status: 'active', emailVerifiedAt: new Date() } });
  const origin = await app.startWeb();
  const browser = await chromium.launch(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : { channel: 'chrome' });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 375, height: 850 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const button = name => page.getByRole('button', { name, exact: true });
  const login = async () => {
    await page.locator('#email').fill(email);
    await page.locator('#password').fill(password);
    await button('Đăng nhập').click();
  };
  await page.goto(origin + '/login');
  await login();
  await page.waitForURL(origin + '/dishes');
  await page.getByRole('link', { name: 'Bảo mật', exact: true }).click();
  await page.locator('input[name=password]').fill('wrong-login-password');
  await button('Bắt đầu thiết lập').click();
  await page.getByText('Mật khẩu đăng nhập Soucha không đúng. Ô này không nhận mã từ ứng dụng xác thực.', { exact: true }).waitFor();
  await page.locator('input[name=password]').fill(password);
  const setupResponse = page.waitForResponse(r => r.url().endsWith('/api/auth/mfa/setup'));
  await button('Bắt đầu thiết lập').click();
  let setup = (await (await setupResponse).json()).data;
  await page.locator('.mfa-qr').waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await app.prisma.mfaCredential.updateMany({ data: { pendingExpiresAt: new Date(Date.now() - 1) } });
  await page.reload();
  await page.getByText('Thiết lập trước đã hết hạn và chưa bật MFA.', { exact: false }).waitFor();
  await page.getByLabel('Mật khẩu đăng nhập Soucha', { exact: true }).fill(password);
  const newSetupResponse = page.waitForResponse(r => r.url().endsWith('/api/auth/mfa/setup'));
  await button('Bắt đầu thiết lập').click();
  setup = (await (await newSetupResponse).json()).data;
  await page.locator('.mfa-qr').waitFor();
  // Reload restores the JWT but never displays the setup secret a second time.
  await page.reload();
  await page.waitForURL(origin + '/account/security');
  await button('Bật xác thực hai lớp').waitFor();
  assert.equal(await button('Bắt đầu thiết lập').count(), 0);
  assert.equal(await page.getByRole('heading', { name: 'Tạo thiết lập mới', exact: true }).count(), 0);
  assert.equal(await page.locator('input[name=password]').count(), 0);
  await page.locator('input[name=code]').waitFor();
  assert.equal(await page.locator('.mfa-qr').count(), 0);
  assert.equal(await page.locator('.mfa-secret').count(), 0);
  // A new password login can also resume the scanned setup.
  await page.evaluate(() => sessionStorage.clear());
  await page.reload();
  await page.waitForURL(origin + '/login');
  await login();
  await page.waitForURL(origin + '/dishes');
  await page.getByRole('link', { name: 'Bảo mật', exact: true }).click();
  await button('Bật xác thực hai lớp').waitFor();
  assert.equal(await page.locator('.mfa-qr').count(), 0);
  assert.equal(await page.locator('.mfa-secret').count(), 0);
  await page.locator('input[name=code]').fill(totp(setup.secret, Math.floor(Date.now() / 30_000)));
  await button('Bật xác thực hai lớp').click();
  await page.locator('.mfa-recovery li').first().waitFor();
  const codes = await page.locator('.mfa-recovery li').allTextContents();
  assert.equal(codes.length, 8);
  await button('Đóng và về bảo mật').click();
  assert.equal(await page.locator('.mfa-recovery').count(), 0);
  await page.getByRole('link', { name: 'Đăng xuất', exact: true }).click();
  await button('Đăng xuất').click();
  await page.waitForURL(origin + '/login');
  const response = page.waitForResponse(r => r.url().endsWith('/api/auth/login'));
  await login();
  const pending = (await (await response).json()).data;
  assert.equal(pending.next, 'mfa');
  assert.equal(pending.accessToken, undefined);
  await page.waitForURL(origin + '/mfa');
  assert.equal((await page.request.get(app.apiUrl + '/api/dishes', { headers: { Authorization: 'Bearer ' + pending.challenge } })).status(), 401);
  assert.equal(await page.evaluate(() => sessionStorage.getItem('soucha-access-token')), null);
  await page.goto(origin + '/admin/dishes');
  await page.waitForURL(origin + '/login');
  await login();
  await page.waitForURL(origin + '/mfa');
  await page.reload();
  await page.waitForURL(origin + '/login');
  await login();
  await page.waitForURL(origin + '/mfa');
  await page.locator('input[name=code]').fill(codes[0]);
  await button('Xác minh và đăng nhập').click();
  await page.waitForURL(origin + '/dishes');
  await page.getByRole('link', { name: 'Bảo mật', exact: true }).click();
  const disableForm = page.locator('form').filter({ has: button('Tắt xác thực hai bước') });
  await disableForm.locator('input[name=password]').fill(password);
  await disableForm.locator('input[name=code]').fill(codes[1]);
  await button('Tắt xác thực hai bước').click();
  await button('Bắt đầu thiết lập').waitFor();
  assert.equal((await app.prisma.mfaCredential.findFirst()).enabled, false);
  assert.equal(await page.evaluate(() => localStorage.length), 0);
  assert.deepEqual(errors, []);
});
